#!/usr/bin/env bun
import { lstat, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const skillsRoot = join(root, '..', '..', 'packages', 'harness', 'skills')
const filesDirectory = join(root, 'src', 'pod', 'builtin-files.generated')
const manifestFile = join(root, 'src', 'pod', 'builtin.generated.ts')

const ENTRY = 'SKILL.md'
const FILES_PER_MODULE = 60
const IGNORED: ReadonlySet<string> = new Set(['.DS_Store'])

const byCodePoint = (left: string, right: string): number =>
  left < right ? -1 : left > right ? 1 : 0

const pathsUnder = async (args: { directory: string; at: string }): Promise<readonly string[]> => {
  const names = (await readdir(join(args.directory, args.at)).catch(() => [])).sort(byCodePoint)
  const found: string[] = []

  for (const name of names) {
    if (IGNORED.has(name)) continue
    const path = args.at === '' ? name : `${args.at}/${name}`
    const info = await lstat(join(args.directory, path))
    if (info.isDirectory()) {
      found.push(...(await pathsUnder({ directory: args.directory, at: path })))
      continue
    }
    if (info.isFile()) found.push(path)
  }

  return found
}

const CONTENT_TYPES: Readonly<Record<string, string>> = {
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.pdf': 'application/pdf',
  '.zip': 'application/zip',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2',
}

const contentTypeOf = (path: string): string =>
  CONTENT_TYPES[path.slice(path.lastIndexOf('.'))] ?? 'application/octet-stream'

type ReadFile = { kind: 'text'; text: string } | { kind: 'binary' }

const readOf = async (path: string): Promise<ReadFile> => {
  const bytes = await readFile(path)
  if (bytes.includes(0)) return { kind: 'binary' }
  const text = bytes.toString('utf8')
  return text.includes('\uFFFD') ? { kind: 'binary' } : { kind: 'text', text }
}

type GeneratedFile = { path: string; text: string } | { path: string; binary: string }

type Generated = { name: string; text: string; files: readonly GeneratedFile[] }

const skillOf = async (name: string): Promise<Generated> => {
  const directory = join(skillsRoot, name)
  const files: GeneratedFile[] = []

  for (const path of await pathsUnder({ directory, at: '' })) {
    if (path === ENTRY) continue
    const read = await readOf(join(directory, path))
    files.push(
      read.kind === 'text' ? { path, text: read.text } : { path, binary: contentTypeOf(path) },
    )
  }

  return { name, text: await readFile(join(directory, ENTRY), 'utf8'), files }
}

const chunked = (files: readonly GeneratedFile[]) => {
  const chunks: GeneratedFile[][] = []
  for (let at = 0; at < files.length; at += FILES_PER_MODULE) {
    chunks.push(files.slice(at, at + FILES_PER_MODULE))
  }
  return chunks
}

const chunkOf = (files: readonly GeneratedFile[]): string =>
  [
    '// GENERATED by plugins/skills/scripts/generate-skills.ts — do not edit.',
    '',
    "import type { BuiltInFile } from '../builtin-files'",
    '',
    'export const FILES: readonly BuiltInFile[] = [',
    ...files.map((file) =>
      'text' in file
        ? `  {\n    path: ${JSON.stringify(file.path)},\n    text: ${JSON.stringify(file.text)},\n  },`
        : `  {\n    path: ${JSON.stringify(file.path)},\n    binary: ${JSON.stringify(file.binary)},\n  },`,
    ),
    ']',
    '',
  ].join('\n')

const manifestOf = (skills: readonly Generated[]): string =>
  [
    '// GENERATED by plugins/skills/scripts/generate-skills.ts — do not edit.',
    '',
    "import type { BuiltInFile } from './builtin-files'",
    ...skills.flatMap((skill, at) =>
      chunked(skill.files).map(
        (_files, index) =>
          `import { FILES as FILES_${at}_${index} } from './builtin-files.generated/${skill.name}-${String(index).padStart(3, '0')}'`,
      ),
    ),
    '',
    'export type BuiltInSkill = { name: string; text: string; files: readonly BuiltInFile[] }',
    '',
    'export const BUILT_IN_SKILLS: readonly BuiltInSkill[] = [',
    ...skills.map(
      (skill, at) =>
        `  {\n    name: ${JSON.stringify(skill.name)},\n    text: ${JSON.stringify(skill.text)},\n    files: [${chunked(
          skill.files,
        )
          .map((_files, index) => `...FILES_${at}_${index}`)
          .join(', ')}],\n  },`,
    ),
    ']',
    '',
  ].join('\n')

export async function generateSkills(): Promise<{
  skills: number
  files: number
  manifestFile: string
}> {
  const names = (await readdir(skillsRoot)).sort(byCodePoint)
  const skills = await Promise.all(names.map(skillOf))

  await rm(filesDirectory, { recursive: true, force: true })
  await mkdir(filesDirectory, { recursive: true })
  for (const skill of skills) {
    const chunks = chunked(skill.files)
    for (const [index, files] of chunks.entries()) {
      await writeFile(
        join(filesDirectory, `${skill.name}-${String(index).padStart(3, '0')}.ts`),
        chunkOf(files),
      )
    }
  }

  await writeFile(manifestFile, manifestOf(skills))
  return {
    skills: skills.length,
    files: skills.reduce((total, skill) => total + skill.files.length, 0),
    manifestFile,
  }
}

if (import.meta.main) {
  const result = await generateSkills()
  console.log(`skills: ${result.skills} built-ins, ${result.files} files → ${result.manifestFile}`)
}
