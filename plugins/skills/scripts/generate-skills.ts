#!/usr/bin/env bun
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const skillsRoot = join(root, 'skills')
const manifestFile = join(root, 'src', 'pod', 'builtin.generated.ts')

const entryOf = async (name: string): Promise<{ name: string; text: string }> => ({
  name,
  text: await readFile(join(skillsRoot, name, 'SKILL.md'), 'utf8'),
})

const byCodePoint = (left: string, right: string): number =>
  left < right ? -1 : left > right ? 1 : 0

export async function generateSkills(): Promise<{ skills: number; manifestFile: string }> {
  const names = (await readdir(skillsRoot)).sort(byCodePoint)
  const skills = await Promise.all(names.map(entryOf))

  const text = [
    '// GENERATED by plugins/skills/scripts/generate-skills.ts — do not edit.',
    '',
    'export type BuiltInSkill = { name: string; text: string }',
    '',
    'export const BUILT_IN_SKILLS: readonly BuiltInSkill[] = [',
    ...skills.map(
      (skill) =>
        `  {\n    name: ${JSON.stringify(skill.name)},\n    text: ${JSON.stringify(skill.text)},\n  },`,
    ),
    ']',
    '',
  ].join('\n')

  await writeFile(manifestFile, text)
  return { skills: skills.length, manifestFile }
}

if (import.meta.main) {
  const result = await generateSkills()
  console.log(`skills: ${result.skills} built-ins → ${result.manifestFile}`)
}
