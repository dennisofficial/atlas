import { afterEach, describe, expect, it } from 'bun:test'

import { toThreadId, type ThreadId } from '@dltech/atlas-core'
import { harness, readied, THREAD } from '@dltech/atlas-client/channel-fixture'

import { EClientRequest } from '../../cloud/channel-wire'
import { openStoreFixture, type StoreFixture } from '../../store/__tests__/harness'
import { createLocalPodTitles } from '../local-pod-titles'

const fixtures: StoreFixture[] = []

afterEach(async () => {
  for (const fixture of fixtures.splice(0)) await fixture.close()
})

async function homeWith(args: { title?: string; threadId?: ThreadId } = {}) {
  const fixture = openStoreFixture()
  fixtures.push(fixture)
  await fixture.threads.create({
    id: args.threadId ?? THREAD,
    workspace: '/w',
    repo: null,
    ...(args.title === undefined ? {} : { title: args.title }),
  })
  return fixture
}

describe('local-pod title authority through the shared adapter', () => {
  it('renames a parked pod locally without sending, attaching, or waking', async () => {
    const home = await homeWith()
    let wakes = 0
    const live = harness({
      unattached: true,
      wakeSandbox: async () => {
        wakes += 1
        return { url: 'https://pod.test', token: 'token' }
      },
    })
    const titles = createLocalPodTitles({
      home: home.home,
      threadId: THREAD,
      channel: () => live.channel,
    })

    await titles.rename({ title: 'User edit' })
    await titles.settled()

    expect((await home.threads.find({ threadId: THREAD }))?.title).toBe('User edit')
    expect(wakes).toBe(0)
    expect(live.sockets).toHaveLength(0)
  })

  it('works with no held channel and persists across adapter instances', async () => {
    const home = await homeWith()
    const titles = createLocalPodTitles({ home: home.home, threadId: THREAD })
    await titles.rename({ title: 'Saved while closed' })

    const reopened = createLocalPodTitles({ home: home.home, threadId: THREAD })
    expect((await reopened.read()).title).toBe('Saved while closed')
  })

  it('forwards to a connected latest-release pod using only the existing rename payload', async () => {
    const home = await homeWith()
    const live = readied()
    const sent: { op: EClientRequest; params: unknown }[] = []
    live.channel.requestIfConnected = async (request) => {
      sent.push(request)
      return {}
    }
    const titles = createLocalPodTitles({
      home: home.home,
      threadId: THREAD,
      channel: () => live.channel,
    })

    await titles.rename({ title: 'New user title' })
    await titles.settled()

    expect(sent).toEqual([
      { op: EClientRequest.RenameThread, params: { threadId: THREAD, title: 'New user title' } },
    ])
  })

  it('accepts an untagged legacy pod title only as an initial auto proposal', async () => {
    const home = await homeWith()
    const titles = createLocalPodTitles({ home: home.home, threadId: THREAD })
    const heard: string[] = []
    titles.onRename((renamed) => heard.push(renamed.title))

    titles.observe({ title: 'Generated by the pod' })
    await titles.settled()
    titles.observe({ title: 'Stale duplicate' })
    await titles.settled()

    expect((await titles.read()).title).toBe('Generated by the pod')
    expect(heard).toEqual(['Generated by the pod'])
  })

  it('protects a named legacy home record even without provenance', async () => {
    const home = await homeWith({ title: 'Existing local name' })
    const titles = createLocalPodTitles({ home: home.home, threadId: THREAD })

    titles.observe({ title: 'Old pod title' })
    await titles.settled()

    expect((await titles.read()).title).toBe('Existing local name')
  })

  it('does not adopt a stale Ready snapshot over a user rename performed during its read', async () => {
    const home = await homeWith()
    const live = readied()
    let answer: (value: unknown) => void = () => undefined
    let reading: () => void = () => undefined
    const readStarted = new Promise<void>((done) => {
      reading = done
    })
    const snapshots = new Promise<unknown>((done) => {
      answer = done
    })
    const sent: unknown[] = []
    live.channel.requestIfConnected = (request) => {
      if (request.op === EClientRequest.ReadThread) {
        reading()
        return snapshots
      }
      sent.push(request.params)
      return Promise.resolve({})
    }
    const titles = createLocalPodTitles({
      home: home.home,
      threadId: THREAD,
      channel: () => live.channel,
    })
    titles.reconcile()
    await readStarted
    await titles.rename({ title: 'User wins' })
    answer({
      thread: {
        id: THREAD,
        title: 'Stale pod name',
        head: 0,
        createdAt: '2026-10-31T00:00:00.000Z',
        updatedAt: '2026-10-31T00:00:00.000Z',
        workspace: '/w',
        repo: null,
      },
    })
    await titles.settled()

    expect((await titles.read()).title).toBe('User wins')
    expect(sent).toContainEqual({ threadId: THREAD, title: 'User wins' })
  })

  it('preserves authority against a delayed title echo after reopening', async () => {
    const home = await homeWith({ threadId: toThreadId('brn_reopened') })
    const args = { home: home.home, threadId: toThreadId('brn_reopened') }
    await createLocalPodTitles(args).rename({ title: 'Saved name' })
    const reopened = createLocalPodTitles(args)

    reopened.observe({ title: 'Outdated pod title' })
    await reopened.settled()

    expect((await reopened.read()).title).toBe('Saved name')
  })
})
