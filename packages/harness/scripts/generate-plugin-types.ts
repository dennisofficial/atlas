import { mkdtemp, readdir, rm } from 'node:fs/promises'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

import { PLUGIN_API_MODULES } from '../src/plugins/api'
import { ATLAS_PLUGIN_SPECIFIER } from '../src/plugins/install-api'
import { GENERATED_PLUGIN_TYPES_FILE } from '../src/plugin-types/constants'

const WORKSPACE_ENTRIES = [
  {
    specifier: "'@dltech/atlas-core'",
    entry: ['packages', 'core', 'src', 'index'],
  },
  {
    specifier: "'@dltech/atlas-wire'",
    entry: ['packages', 'wire', 'src', 'index'],
  },
]

const DECLARATION_ENTRIES = [
  ['packages', 'core', 'src', 'index.ts'],
  ['packages', 'wire', 'src', 'index.ts'],
  ['packages', 'harness', 'src', 'plugins', 'plugin.ts'],
]

const declarationFilesIn = async (directory: string): Promise<readonly string[]> => {
  const entries = await readdir(directory, {
    withFileTypes: true,
    recursive: true,
  })
  return entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.d.ts'))
    .map((entry) => join(entry.parentPath, entry.name))
}

// The emitted declarations import '@dltech/atlas-core' by name, and a plugin author's project has
// no such package. Pointing them at their own sibling declarations is what makes the shipped types
// resolve on their own; without it every core type silently degrades to any under skipLibCheck.
const resolveWorkspaceImports = async (declarationRoot: string): Promise<void> => {
  for (const path of await declarationFilesIn(declarationRoot)) {
    let text = await Bun.file(path).text()
    let changed = false
    for (const { specifier, entry } of WORKSPACE_ENTRIES) {
      if (!text.includes(specifier)) continue
      const toEntry = relative(dirname(path), join(declarationRoot, ...entry))
      const resolved = toEntry.startsWith('.') ? toEntry : `./${toEntry}`
      text = text.replaceAll(specifier, `'${resolved}'`)
      changed = true
    }
    if (changed) await Bun.write(path, text)
  }
}

export async function emitPluginDeclarations(args: {
  sourceRoot: string
  declarationRoot: string
}): Promise<void> {
  const emitted = Bun.spawn(
    [
      'bunx',
      'tsc',
      '--ignoreConfig',
      '--declaration',
      '--emitDeclarationOnly',
      '--outDir',
      args.declarationRoot,
      '--rootDir',
      args.sourceRoot,
      '--target',
      'ES2023',
      '--lib',
      'ES2023,DOM',
      '--module',
      'Preserve',
      '--moduleResolution',
      'bundler',
      '--strict',
      '--skipLibCheck',
      '--types',
      'bun',
      ...DECLARATION_ENTRIES.map((entry) => join(args.sourceRoot, ...entry)),
    ],
    {
      cwd: join(args.sourceRoot, 'packages', 'harness'),
      stdout: 'pipe',
      stderr: 'pipe',
    },
  )

  const code = await emitted.exited
  if (code !== 0) {
    throw new Error(
      `tsc emitted no declarations (${code}): ${await new Response(emitted.stdout).text()}`,
    )
  }

  await resolveWorkspaceImports(args.declarationRoot)
}

const BUNDLER_HEADER = /^\/\/ Generated by dts-bundle-generator.*\n/
const EMPTY_EXPORT = /^export \{\};?\s*$/m

const entryDeclaration = (): string =>
  PLUGIN_API_MODULES.map((module) => {
    const values = [...module.values]
    const types = [...module.valueTypes.filter((name) => !values.includes(name)), ...module.types]
    const names = [...values, ...types.map((name) => `type ${name}`)]
    return `export { ${names.join(', ')} } from './${module.path.join('/')}'`
  })
    .concat('')
    .join('\n')

const BUNDLE_TSCONFIG = {
  compilerOptions: {
    target: 'ES2023',
    lib: ['ES2023', 'DOM'],
    module: 'Preserve',
    moduleResolution: 'bundler',
    strict: true,
    skipLibCheck: true,
    types: ['bun'],
  },
}

const ambientModule = (bundled: string): string => {
  const body = bundled
    .replace(BUNDLER_HEADER, '')
    .replace(EMPTY_EXPORT, '')
    .replace(/^(export )?declare /gm, '$1')
    .trim()
  return `declare module '${ATLAS_PLUGIN_SPECIFIER}' {\n${body}\n}\n`
}

export async function buildPluginTypes(args: { sourceRoot: string }): Promise<string> {
  const work = await mkdtemp(join(args.sourceRoot, 'packages', 'harness', '.plugin-types-'))
  try {
    const declarationRoot = join(work, 'declarations')
    await emitPluginDeclarations({
      sourceRoot: args.sourceRoot,
      declarationRoot,
    })

    const entry = join(declarationRoot, 'entry.d.ts')
    const config = join(declarationRoot, 'tsconfig.json')
    const bundle = join(work, 'atlas.bundle.d.ts')
    await Bun.write(entry, entryDeclaration())
    await Bun.write(config, JSON.stringify(BUNDLE_TSCONFIG))

    const bundled = Bun.spawn(
      [
        'bunx',
        'dts-bundle-generator',
        '--no-check',
        '--external-inlines',
        'zod',
        '--export-referenced-types=false',
        '--project',
        config,
        '-o',
        bundle,
        entry,
      ],
      {
        cwd: join(args.sourceRoot, 'packages', 'harness'),
        stdout: 'pipe',
        stderr: 'pipe',
      },
    )
    const code = await bundled.exited
    if (code !== 0) {
      throw new Error(
        `dts-bundle-generator failed (${code}): ${await new Response(bundled.stderr).text()}`,
      )
    }

    return ambientModule(await Bun.file(bundle).text())
  } finally {
    await rm(work, { recursive: true, force: true })
  }
}

export const workspaceRootOfThisScript = (): string =>
  join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')

export async function generatePluginTypes(): Promise<string> {
  const root = workspaceRootOfThisScript()
  const text = await buildPluginTypes({ sourceRoot: root })
  const outFile = join(root, ...GENERATED_PLUGIN_TYPES_FILE)
  await Bun.write(
    outFile,
    [
      '// GENERATED by packages/harness/scripts/generate-plugin-types.ts — do not edit.',
      '',
      `export const PLUGIN_TYPES_TEXT = ${JSON.stringify(text)}`,
      '',
    ].join('\n'),
  )
  return outFile
}

if (import.meta.main) {
  console.log(`plugin types → ${await generatePluginTypes()}`)
}
