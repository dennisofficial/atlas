import { parseSkillSpec, skillFallbackNameOf } from '../src/skill-specs/parse'

const quoted = (text: string): string => JSON.stringify(text)

export function skillSpecsModule(skills: readonly { entryPath: string; text: string }[]): string {
  const lines = skills.flatMap((skill) => {
    const parsed = parseSkillSpec({
      text: skill.text,
      fallbackName: skillFallbackNameOf(skill.entryPath),
    })
    if (parsed === undefined || !parsed.userInvocable) return []
    const { name, summary, argumentHint } = parsed.spec
    const hint = argumentHint === undefined ? '' : `, argumentHint: ${quoted(argumentHint)}`
    return [`  { name: ${quoted(name)}, summary: ${quoted(summary)}${hint} },`]
  })

  return [
    '// GENERATED by packages/harness/scripts/generate-skills.ts — do not edit.',
    '',
    "import type { BuiltInSkillSpec } from './types'",
    '',
    'export const BUILT_IN_SKILL_SPECS: readonly BuiltInSkillSpec[] = [',
    ...lines,
    ']',
    '',
  ].join('\n')
}
