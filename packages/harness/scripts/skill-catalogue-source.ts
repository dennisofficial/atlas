import { parseFrontmatter, skillFrontmatterOf } from '@dltech/atlas-core'

const quoted = (text: string): string => JSON.stringify(text)

const TEXT_EXTENSIONS: ReadonlySet<string> = new Set([
  'md',
  'txt',
  'json',
  'yaml',
  'yml',
  'ts',
  'tsx',
  'js',
  'jsx',
  'mjs',
  'cjs',
  'toml',
  'sh',
  'py',
  'rb',
  'go',
  'rs',
  'css',
  'html',
  'xml',
  'svg',
])

const extensionOf = (path: string): string => path.slice(path.lastIndexOf('.') + 1).toLowerCase()

export type SkillCatalogueSource = {
  entryPath: string
  text: string
  entryDigest: string
  resources: readonly { path: string; digest: string; sizeBytes: number }[]
}

export function skillCatalogueModule(skills: readonly SkillCatalogueSource[]): string {
  const lines = skills.flatMap((skill) => {
    const name = skill.entryPath.split('/')[0] ?? ''
    const description = skillFrontmatterOf({
      document: parseFrontmatter(skill.text).document,
      fallbackName: name,
    }).description
    const updatedAt = new Date(0).toISOString()
    const files = skill.resources.map(
      (resource) =>
        `      { path: ${quoted(resource.path)}, digest: ${quoted(resource.digest)}, sizeBytes: ${resource.sizeBytes}, isText: ${TEXT_EXTENSIONS.has(extensionOf(resource.path))} },`,
    )
    return [
      `  {`,
      `    name: ${quoted(name)},`,
      `    description: ${quoted(description)},`,
      `    updatedAt: ${quoted(updatedAt)},`,
      `    entry: { path: 'SKILL.md', digest: ${quoted(skill.entryDigest)}, sizeBytes: ${Buffer.byteLength(skill.text, 'utf8')} },`,
      `    files: [`,
      ...files,
      `    ],`,
      `  },`,
    ]
  })

  return [
    '// GENERATED by packages/harness/scripts/generate-skills.ts — do not edit.',
    '',
    "import type { BuiltInSkillCatalogueEntry } from './catalogue-types'",
    '',
    'export const BUILT_IN_SKILL_CATALOGUE: readonly BuiltInSkillCatalogueEntry[] = [',
    ...lines,
    ']',
    '',
  ].join('\n')
}
