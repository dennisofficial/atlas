const LANGUAGE_BY_FILENAME: Record<string, ShikiLanguage> = {
  dockerfile: 'dockerfile',
  gemfile: 'ruby',
  rakefile: 'ruby',
  '.bashrc': 'bash',
  '.zshrc': 'bash',
  '.env': 'ini',
  '.vimrc': 'viml',
}

export function languageOfPath(path: string): ShikiLanguage | null {
  const name = (path.split('/').pop() ?? '').toLowerCase()
  const byName = LANGUAGE_BY_FILENAME[name]
  if (byName !== undefined) return byName
  const dot = name.lastIndexOf('.')
  if (dot <= 0) return null
  return LANGUAGE_BY_EXTENSION[name.slice(dot + 1)] ?? null
}
